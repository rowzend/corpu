import os
import subprocess
import tempfile
import shutil
from pathlib import Path
from io import BytesIO
from django.core.files.base import ContentFile


def _find_libreoffice():
    """Auto-detect LibreOffice executable path."""
    path = shutil.which('soffice') or shutil.which('libreoffice')
    if path:
        return path
    common_paths = [
        '/usr/bin/soffice',
        '/usr/bin/libreoffice',
        '/usr/local/bin/soffice',
    ]
    for p in common_paths:
        if os.path.exists(p):
            return p
    return None


def render_docx_to_pdf(template_bytes, context, filename='template.docx', image_fields=None):
    """Render a DOCX/PPTX template with context variables then convert to PDF.

    Args:
        template_bytes: Raw bytes of the .docx or .pptx file.
        context: Dict of variables for Jinja2 rendering (strings, numbers, etc).
        filename: Original filename to detect extension.
        image_fields: Dict of {field_name: (image_bytes, mime_ext)} for inline images.
            Images are embedded as InlineImage objects by docxtpl.

    Returns:
        PDF bytes.
    """
    from docxtpl import DocxTemplate, InlineImage as DocxInlineImage
    from docx.shared import Inches

    libreoffice = _find_libreoffice()
    if not libreoffice:
        raise FileNotFoundError(
            'LibreOffice not found. Install libreoffice-core on the system.'
        )

    suffix = Path(filename).suffix.lower() or '.docx'
    is_pptx = suffix == '.pptx'

    with tempfile.TemporaryDirectory() as tmp_dir:
        template_path = Path(tmp_dir) / f'template{suffix}'
        template_path.write_bytes(template_bytes)

        rendered_path = Path(tmp_dir) / f'rendered{suffix}'
        pdf_dir = Path(tmp_dir) / 'output'
        pdf_dir.mkdir()

        if not is_pptx:
            tpl = DocxTemplate(str(template_path))

            if image_fields:
                for field_name, (img_data, img_ext, width) in image_fields.items():
                    if img_data:
                        img_stream = BytesIO(img_data)
                        context[field_name] = DocxInlineImage(tpl, img_stream, width=Inches(width))

            tpl.render(context)
            tpl.save(str(rendered_path))
        else:
            shutil.copy2(template_path, rendered_path)

        result = subprocess.run(
            [
                libreoffice,
                '--headless',
                '--convert-to', 'pdf',
                '--outdir', str(pdf_dir),
                str(rendered_path),
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )

        if result.returncode != 0:
            raise RuntimeError(f'LibreOffice conversion failed: {result.stderr}')

        pdf_files = list(pdf_dir.glob('*.pdf'))
        if not pdf_files:
            raise FileNotFoundError('PDF was not generated by LibreOffice')

        return pdf_files[0].read_bytes()


def docx_to_pdf_raw(template_bytes):
    """Convert DOCX/PPTX to PDF without template rendering (no variable substitution).

    Args:
        template_bytes: Raw bytes of the .docx or .pptx file.

    Returns:
        PDF bytes.
    """
